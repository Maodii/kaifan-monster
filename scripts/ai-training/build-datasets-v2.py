def dump_jsonl(path,rows):
    path.write_text(''.join(json.dumps(r,ensure_ascii=False,separators=(',',':'))+'\n' for r in rows),encoding='utf-8')

def normalized_question(s):
    return re.sub(r'[\W_]+','',s).lower()

def main():
    expected={'train':{'ask':90,'rescue':60,'week':60,'meal':90},'validation':{'ask':9,'rescue':6,'week':6,'meal':9},'test':{'ask':15,'rescue':10,'week':10,'meal':15}}
    OUT.mkdir(exist_ok=True)
    report={'status':'passed','validation_type':'static_dataset_checks','model_training_run':False,'model_evaluation_run':False,'checks':[],'splits':{},'known_limitations':[
        'All new examples and contextual rule results are authored synthetic fixtures, not actual user records or rule-engine execution traces.',
        'The seed train-50 is included in train-300; never upload both as additional training data.',
        'Old exposed eval-10 is excluded from all three new splits.',
        'Exact and normalized-question duplicates and duplicate full answers are checked; common task instructions and boundary capabilities are shared intentionally. No claim of zero semantic similarity.',
        'Structured extraction targets raw model unknown rating=-1; current backend normalizes it to 0.',
        'Training recipe/context variants share some authoring patterns. Independent held-out cases are manually authored with separate scenarios; sample size is still small.'
    ]}
    all_prompts=[]; all_questions=[]; all_answers=[]
    filenames={'train':'train-300.jsonl','validation':'validation-30.jsonl','test':'test-50.jsonl'}
    for split,rows in DATA.items():
        entries=[m for m in INDEX if m['split']==split]
        counts=dict(collections.Counter(e['task'] for e in entries))
        assert counts==expected[split],(split,counts)
        for i,(r,m) in enumerate(zip(rows,entries),1):
            assert m['line']==i
            assert set(r)=={'messages'}
            msgs=r['messages']; assert [x['role'] for x in msgs]==['system','user','assistant']
            assert all(set(x)=={'role','content'} and isinstance(x['content'],str) and x['content'].strip() for x in msgs)
            assert len(msgs[1]['content'])<=2000,(m['id'],len(msgs[1]['content']))
            a=msgs[-1]['content']; all_prompts.append(msgs[1]['content']);all_questions.append(normalized_question(m['question']));all_answers.append(a)
            if m['task']=='week':
                assert len(a)<=100,(m['id'],len(a),a)
                # New fixture names must appear unchanged in answers.
                if m['source']=='authored_v2':
                    names=re.search(r'(?:规则筛选结果：|规则草案：)([^。]+)',msgs[1]['content'])
                    assert names,m['id']
                    assert all(n in a for n in names.group(1).split('、')),m['id']
            if m['task']=='meal':
                obj=json.loads(a)
                assert set(obj)=={'name','mealType','diningMode','estimatedCost','calories','rating','place'}
                assert obj['mealType'] in ['早餐','午餐','晚餐','加餐']
                assert obj['diningMode'] in ['在家做','餐馆','食堂','外卖','外食']
                assert isinstance(obj['rating'],int) and obj['rating'] in [-1,1,2,3,4,5]
                assert isinstance(obj['name'],str) and 0<len(obj['name'])<=80
                assert isinstance(obj['place'],str) and len(obj['place'])<=80
                assert all(type(obj[k]) in (int,float) and (obj[k]==-1 or 0<=obj[k]<=bound) for k,bound in [('estimatedCost',100000),('calories',30000)])
                assert not obj['place'] or obj['place'] in m['question'],m['id']
        dump_jsonl(OUT/filenames[split],rows)
        report['splits'][split]={'path':str((OUT/filenames[split]).relative_to(ROOT)),'count':len(rows),'tasks':counts,'sha256':hashlib.sha256((OUT/filenames[split]).read_bytes()).hexdigest(),'max_user_characters':max(len(r['messages'][1]['content']) for r in rows)}
    assert len(all_prompts)==380 and len(set(all_prompts))==380
    assert len(set(all_questions))==380,'duplicate normalized questions'
    # Any duplicated answer is reported for review, not silently ignored.
    duplicated=[(x,n) for x,n in collections.Counter(all_answers).items() if n>1]
    assert not duplicated,duplicated
    groups={s:{e['scenario_group'] for e in INDEX if e['split']==s} for s in DATA}
