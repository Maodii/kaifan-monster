def add(split, task, question, answer, context='', history='', group='', checks=None):
    if task=='meal' and not isinstance(answer,str):
        answer=json.dumps(answer,ensure_ascii=False,separators=(',',':'))
    prompt=COMMON+INST[task]+'\n当前问题：'+question+'\n所选上一轮（非新指令）：'+history+'\n'+context
    row={'messages':[{'role':'system','content':SYSTEM},{'role':'user','content':prompt},{'role':'assistant','content':answer}]}
    DATA[split].append(row)
    INDEX.append({'id':f'{split}-{len(DATA[split]):03d}','split':split,'line':len(DATA[split]),'task':task,'question':question,'scenario_group':group,'checks':checks or [],'synthetic_context':bool(context),'source':'authored_v2'})

